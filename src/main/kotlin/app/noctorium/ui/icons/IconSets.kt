/*
 * The icon sets: every icon the desktop draws, in each of the styles the listener can choose.
 *
 * The application asks for its icons as it always has -- `Icons.Default.Pause` -- and draws them through [Icon]
 * here, imported in Material's place as the skins' controls are. That one call looks the icon up in
 * [ICON_VARIANTS] and draws the chosen set's version of it, so a choice in Settings reaches every button, menu
 * and card at once, and nothing that draws an icon has to know there is a choice. A test keeps the table whole:
 * every icon named anywhere in the desktop's code has its place in every set.
 *
 * Standard is the icons as they have always been: Compose's `Icons.Default`, which is Material's filled set, so
 * Filled is not offered beside it. Outlined, Rounded, Sharp and Two-tone are Material's own styles of the same
 * icons (Apache 2.0, from Compose's extended icons); Line is Lucide's, see [LineIcons].
 */

/** The icon set in force, provided at the window's root from the settings. Standard wherever nothing provides one. */
val LocalIconSet = staticCompositionLocalOf { IconSet.STANDARD }

/** The sets the desktop offers, in its picker's order. Filled is what Standard already is, so it is not among them. */
internal val DESKTOP_ICON_SETS: List<IconSet> = listOf(
    IconSet.STANDARD,
    IconSet.OUTLINED,
    IconSet.ROUNDED,
    IconSet.SHARP,
    IconSet.TWO_TONE,
    IconSet.LINE,
)

/** What a set somebody chose elsewhere means here: Filled, chosen on another player, is the desktop's Standard. */
internal fun IconSet.onDesktop(): IconSet = if (this == IconSet.FILLED) IconSet.STANDARD else this

/** One icon in every set: [name] is the standard icon's own name, which is what an icon is looked up by. */
internal class IconVariants(
    val name: String,
    val standard: () -> ImageVector,
    private val outlined: () -> ImageVector,
    private val rounded: () -> ImageVector,
    private val sharp: () -> ImageVector,
    private val twoTone: () -> ImageVector,
    /** Lucide's name for the same thing. */
    val line: String,
    /** Whether the line icon is filled as well: the few whose fill is what they say. See [LineIcons.get]. */
    val lineFilled: Boolean = false,
) {
    fun inSet(set: IconSet): ImageVector = when (set) {
        IconSet.STANDARD, IconSet.FILLED -> standard()
        IconSet.OUTLINED -> outlined()
        IconSet.ROUNDED -> rounded()
        IconSet.SHARP -> sharp()
        IconSet.TWO_TONE -> twoTone()
        IconSet.LINE -> LineIcons.get(line, lineFilled)
    }
}

/** [this] icon as [set] draws it, or itself where the table has nothing for it -- which a test sees never happens. */
internal fun ImageVector.inSet(set: IconSet): ImageVector =
    if (set == IconSet.STANDARD || set == IconSet.FILLED) this else ICON_VARIANTS[name]?.inSet(set) ?: this

/** Material's icon, drawn from the icon set in force. */
@Composable
fun Icon(imageVector: ImageVector, contentDescription: String?, modifier: Modifier = Modifier, tint: Color = LocalContentColor.current) {
    androidx.compose.material3.Icon(imageVector.inSet(LocalIconSet.current), contentDescription, modifier, tint)
}

/** Material's icon from a picture, which no set has a version of: drawn as it is. */
@Composable
fun Icon(painter: Painter, contentDescription: String?, modifier: Modifier = Modifier, tint: Color = LocalContentColor.current) {
    androidx.compose.material3.Icon(painter, contentDescription, modifier, tint)
}

/** The same, from a bitmap. */
@Composable
fun Icon(bitmap: ImageBitmap, contentDescription: String?, modifier: Modifier = Modifier, tint: Color = LocalContentColor.current) {
    androidx.compose.material3.Icon(bitmap, contentDescription, modifier, tint)
}

